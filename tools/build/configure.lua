local ninja = require("ninja")

-- Map holding all option handlers. Each handler receives (opts, args) and
-- stores its parsed value directly into opts.
local opt_map = {}

-- Short aliases for long options.
local opt_alias = {
  h = "help", ["?"] = "help", V = "version",
  t = "toolkit", c = "config", o = "type",
  v = "verbose", q = "quiet",
}

function opt_map.help(opts, args)
  stdout:write(_info.label .. " -- ", _info.description, ".\n")
  stdout:write(_info.label .. " ", _info.version, " ", _info.release, "\t", _info.url, "\n")
  stdout:write(_usage)
  exit(0)
end

-- Print version information.
function opt_map.version(opts, args)
  stdout:write(format("%s version %s, released %s\n%s\n",
    _info.name, _info.version, _info.release, _info.url
  ))
  exit(0)
end

function opt_map.toolkit(opts, args)
  opts.toolkit = lower(ninja.optparam(args))
end

function opt_map.config(opts, args)
  local v = lower(ninja.optparam(args))
  if v == "release" then opts.config = "release"
  elseif v == "debug" then opts.config = "debug"
  else ninja.opterror("invalid --config `", v, "'; expected `release' or `debug'.") end
end

function opt_map.type(opts, args)
  local v = lower(ninja.optparam(args))
  if v == "static" then opts.type = "static"
  elseif v == "shared" then opts.type = "shared"
  else ninja.opterror("invalid --type `", v, "'; expected `static' or `shared'.") end
end

opt_map["target-os"] = function(opts, args)
  local v = ninja.optparam(args)
  local lv = lower(v)
  if lv ~= "windows" and lv ~= "linux" and lv ~= "macos" then
    ninja.opterror("invalid --target-os `", v, "'; expected `windows', `linux' or `macos'.")
  end
  opts.target_os = lv
end

opt_map["build-dir"] = function(opts, args)
  opts.build_dir = ninja.optparam(args)
end

opt_map["install-dir"] = function(opts, args)
  opts.install_dir = ninja.optparam(args)
end

opt_map["with-tests"] = function(opts, args)
  opts.with_tests = true
end

opt_map["with-bench"] = function(opts, args)
  opts.with_bench = true
end

opt_map["without-ffi"] = function(opts, args)
  opts.with_ffi = false
end

function opt_map.verbose(opts, args)
  opts.verbosity = opts.verbosity + 1
end

function opt_map.quiet(opts, args)
  opts.verbosity = opts.verbosity - 1
end


-- Guess a toolkit from the environment. Returns nil (never a default
-- string) when nothing conclusive is found -- toolkit must then be given
-- explicitly via -t/--toolkit.
local function detect_toolkit()
  if getenv("VCINSTALLDIR") or getenv("VSCMD_ARG_TGT_ARCH") or getenv("VisualStudioVersion") then
    return "msvc"
  end
  local cc = getenv("CC")
  if cc then
    if match(cc, "cl%.exe$") or match(cc, "^cl$") then return "msvc" end
    return "gcc"
  end
  return nil
end

-- Guess the target OS. msvc implies windows; otherwise fall back to
-- whatever hints the environment/host offer. Returns nil if nothing
-- conclusive is found.
local function detect_target_os(opts)
  if opts.toolkit == "msvc" then return "windows" end
  local osenv = getenv("OS")
  if osenv and match(osenv, "Windows") then return "windows" end
  if package and package.config then
    local sep = sub(package.config, 1, 1)
    if sep == "\\" then return "windows" end
  end
  return nil
end

local function defaults()
  return {
    toolkit = detect_toolkit(),
    config = "debug",
    type = "shared",
    target_os = nil,
    build_dir = "build",
    install_dir = nil,
    with_tests = false,
    with_bench = false,
    with_ffi = true,
    verbosity = 0,
    src_dir = ".",
  }
end

local function main(args)
  local opts = ninja.parseargs(args, defaults(), opt_map, opt_alias)

  if not opts.toolkit then
    ninja.opterror("no toolkit specified and none could be detected from ",
      "the environment; use -t/--toolkit (msvc or gcc).")
  end
  if opts.toolkit ~= "msvc" and opts.toolkit ~= "gcc" then
    ninja.opterror("unrecognized toolkit `", opts.toolkit, "'; expected `msvc' or `gcc'.")
  end

  opts.target_os = opts.target_os or detect_target_os(opts)
  if not opts.target_os then
    ninja.opterror("could not detect the target OS; use --target-os ",
      "(windows, linux or macos).")
  end

  generate(ninja, opts)
end


main({...})
