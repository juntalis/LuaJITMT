-- Generate toolkit configuration: compiler/linker/archiver + flags pulled
-- from the environment where available (CC/LD/AR/CFLAGS/LDFLAGS/ARFLAGS).
local function gen_tools(ninja, opts)
  local tools = ninja.Writer("tools.ninja")
  tools:comment("Toolkit configuration -- generated by configure.lua")
  tools:variable("ninja", getenv("NINJA") or "ninja")
  tools:newline()

  local cflags = getenv("CFLAGS") or ""
  local ldflags = getenv("LDFLAGS") or ""
  local arflags = getenv("ARFLAGS") or ""

  if opts.toolkit == "msvc" then
    tools:variable("cc", getenv("CC") or "cl.exe")
    tools:variable("ld", getenv("LD") or "link.exe")
    tools:variable("ar", getenv("AR") or "lib.exe")
    tools:newline()
    if opts.config == "release" then
      cflags = "/nologo /O2 /DNDEBUG /MD " .. cflags
    else
      cflags = "/nologo /Od /Zi /MDd " .. cflags
    end
  elseif opts.toolkit == "gcc" then
    tools:variable("cc", getenv("CC") or "gcc")
    tools:variable("ld", getenv("LD") or getenv("CC") or "gcc")
    tools:variable("ar", getenv("AR") or "ar")
    tools:newline()
    if opts.config == "release" then
      cflags = "-O2 -DNDEBUG " .. cflags
    else
      cflags = "-O0 -g " .. cflags
    end
  end

  tools:variable("cflags", cflags)
  tools:variable("ldflags", ldflags)
  tools:variable("arflags", arflags)
  tools:close()
end

-- Generate luajit-specific build flags (config.ninja): DASM assembler
-- flags, feature defines, and platform system libraries. This fork only
-- supports x64 (see src/lj_arch.h), so the DASM_TESTARCH probe the
-- Makefile performs via `$(TARGET_CC) -E lj_arch.h -dM` is replaced with a
-- fixed x64 flag set, conditioned only on target OS and --without-ffi.
local function gen_config(ninja, opts)
  local config = ninja.Writer("config.ninja")
  config:comment("LuaJIT feature configuration -- generated by configure.lua")

  local windows = opts.target_os == "windows"

  local dasm_aflags = { "-D", "ENDIAN_LE", "-D", "P64", "-D", "JIT" }
  if opts.with_ffi then
    insert(dasm_aflags, "-D"); insert(dasm_aflags, "FFI")
  end
  insert(dasm_aflags, "-D"); insert(dasm_aflags, "FPU")
  insert(dasm_aflags, "-D"); insert(dasm_aflags, "HFABI")
  insert(dasm_aflags, "-D"); insert(dasm_aflags, "VER=21")
  if windows then
    insert(dasm_aflags, "-D"); insert(dasm_aflags, "WIN")
  end

  local xcflags = {}
  if not opts.with_ffi then
    insert(xcflags, "-DLUAJIT_DISABLE_FFI")
  end
  -- LUA_BUILD_AS_DLL only needs to apply to the objects going into the
  -- shared library itself (see gen_build's "cc_dll" rule), not here, since
  -- this xcflags list is also used to compile luajit.c.

  local syslibs = {}
  if windows then
    if opts.toolkit == "msvc" then
      insert(syslibs, "Synchronization.lib")
    else
      insert(syslibs, "-lsynchronization")
    end
  elseif opts.target_os == "macos" then
    insert(syslibs, "-lm")
  else -- linux and other POSIX targets
    insert(syslibs, "-lm"); insert(syslibs, "-ldl"); insert(syslibs, "-pthread")
  end

  config:variable("dasm_aflags", dasm_aflags)
  config:variable("xcflags", xcflags)
  config:variable("syslibs", syslibs)
  config:newline()
  config:variable("target_os", opts.target_os)
  config:variable("target_ljarch", "x64")
  config:close()
end

-- Configure actual build implementation: minilua -> dynasm -> buildvm ->
-- codegen -> core objects -> static lib -> luajit executable. Mirrors the
-- two-stage bootstrap in src/Makefile using only the requested toolkit's
-- compiler/linker/archiver (never `make`/`nmake`).
local function gen_build(ninja, opts)
  local build = ninja.Writer("build.ninja")
  build:comment("LuaJIT build -- generated by configure.lua. Do not edit.")
  build:include("tools.ninja")
  build:include("config.ninja")
  build:newline()

  local srcdir = opts.src_dir
  local builddir = opts.build_dir
  local windows = opts.target_os == "windows"
  local msvc = opts.toolkit == "msvc"
  local shared = opts.type == "shared"
  local exe_ext = windows and ".exe" or ""
  local quiet = opts.verbosity <= 0

  local function basename(path)
    return match(path, "([^/\\]+)$")
  end

  local function desc(fmt)
    if quiet then return { description = fmt } end
    return nil
  end

  build:variable("builddir", builddir)
  build:newline()

  -- Compile / link / archive rules, tailored to the selected toolkit.
  if msvc then
    build:rule("cc", "$cc /c $cflags $xcflags /I" .. srcdir .. " /Fo$out $in",
                desc("CC $out"))
    build:rule("hostlink", "$ld /nologo $ldflags /out:$out $in",
                desc("LINK $out"))
    build:rule("ar", "$ar /nologo $arflags /out:$out $in",
                desc("AR $out"))
    build:rule("link", "$ld /nologo $ldflags /out:$out $in $syslibs",
                desc("LINK $out"))
  else
    build:rule("cc", "$cc $cflags $xcflags -I" .. srcdir .. " -c -o $out $in",
                desc("CC $out"))
    build:rule("hostlink", "$cc $ldflags -o $out $in -lm",
                desc("LINK $out"))
    build:rule("ar", "$ar $arflags $out $in",
                desc("AR $out"))
    build:rule("link", "$cc $ldflags -o $out $in $syslibs",
                desc("LINK $out"))
  end

  -- The objects going into the shared library need an extra define/flag
  -- that the static-library and exe-only objects don't: LUA_BUILD_AS_DLL
  -- on Windows (so luaconf.h's LUA_API resolves to dllexport instead of
  -- dllimport) or -fPIC on POSIX.
  if shared then
    local extra = windows and "-DLUA_BUILD_AS_DLL " or "-fPIC "
    if msvc then
      build:rule("cc_dll", "$cc /c $cflags $xcflags " .. extra .. "/I" .. srcdir .. " /Fo$out $in",
                  desc("CC $out"))
      build:rule("dll", "$ld /nologo /DLL $ldflags /out:$out /IMPLIB:$implib $in $syslibs",
                  desc("LINK $out"))
    else
      build:rule("cc_dll", "$cc $cflags $xcflags " .. extra .. "-I" .. srcdir .. " -c -o $out $in",
                  desc("CC $out"))
      if windows then
        build:rule("dll", "$cc -shared $ldflags -o $out -Wl,--out-implib,$implib $in $syslibs",
                    desc("LINK $out"))
      elseif opts.target_os == "macos" then
        build:rule("dll", "$cc -dynamiclib $ldflags -o $out $in $syslibs",
                    desc("LINK $out"))
      else
        build:rule("dll", "$cc -shared $ldflags -o $out $in $syslibs",
                    desc("LINK $out"))
      end
    end
  end
  build:newline()

  build:rule("dynasm",
    "$minilua_exe " .. srcdir .. "/../dynasm/dynasm.lua $dasm_aflags -o $out $in",
    desc("DYNASM $out"))
  build:rule("buildvm_gen", "$buildvm_exe -m $mode -o $out $in",
    desc("BUILDVM $out"))
  build:rule("genversion",
    "$minilua_exe " .. srcdir .. "/host/genversion.lua $in $relver $out",
    desc("VERSION $out"))
  if windows then
    build:rule("relver",
      "cmd /c \"git -C " .. srcdir .. "/.. show -s --format=%%ct > $out 2>nul || echo ROLLING> $out\"",
      desc("RELVER $out"))
    build:rule("copy", "cmd /c copy /y $in $out", desc("INSTALL $out"))
  else
    build:rule("relver",
      "git -C " .. srcdir .. "/.. show -s --format=%ct > $out 2>/dev/null || echo ROLLING > $out",
      desc("RELVER $out"))
    build:rule("copy", "cp $in $out", desc("INSTALL $out"))
  end
  build:newline()

  -- Stage 1: minilua, the host Lua interpreter used to drive DynASM and
  -- the version-stamping script.
  -- cmd.exe refuses to resolve a relative executable path that starts a
  -- command line when it uses forward slashes (`out/minilua.exe` fails to
  -- launch; `out\minilua.exe` works) even though forward slashes are fine
  -- everywhere else as plain arguments. minilua_exe/buildvm_exe are both
  -- invoked that way, so on Windows they're built with backslashes.
  local pathsep = windows and "\\" or "/"

  local minilua_obj = builddir .. "/minilua.obj"
  local minilua_exe = builddir .. pathsep .. "minilua" .. exe_ext
  build:build(minilua_obj, "cc", srcdir .. "/host/minilua.c")
  build:build(minilua_exe, "hostlink", minilua_obj)
  build:variable("minilua_exe", minilua_exe)
  build:newline()

  -- luajit.h version stamping (best-effort; falls back to "ROLLING" when
  -- git metadata isn't available, same as the Makefile's GIT_RELVER step).
  local relver_txt = builddir .. "/luajit_relver.txt"
  build:build(relver_txt, "relver", {})
  build:variable("relver", relver_txt)
  local luajit_h = srcdir .. "/luajit.h"
  build:build(luajit_h, "genversion", srcdir .. "/luajit_rolling.h",
    { relver_txt, minilua_exe })
  build:newline()

  -- Stage 2: run DynASM over the x64 backend to produce buildvm_arch.h.
  local buildvm_arch_h = srcdir .. "/host/buildvm_arch.h"
  local dasm_dasc = srcdir .. "/vm_x64.dasc"
  build:build(buildvm_arch_h, "dynasm", dasm_dasc,
    { minilua_exe, srcdir .. "/lj_arch.h", srcdir .. "/lua.h", srcdir .. "/luaconf.h" })
  build:newline()

  -- Build the buildvm host tool.
  local buildvm_objs = {}
  for _, f in ipairs(BUILDVM_C) do
    local obj = builddir .. "/" .. gsub(f, "%.c$", ".obj")
    build:build(obj, "cc", srcdir .. "/" .. f, { buildvm_arch_h })
    insert(buildvm_objs, obj)
  end
  local buildvm_exe = builddir .. pathsep .. "buildvm" .. exe_ext
  build:build(buildvm_exe, "hostlink", buildvm_objs)
  build:variable("buildvm_exe", buildvm_exe)
  build:newline()

  local ljlib_paths = {}
  for _, f in ipairs(LJLIB_C) do insert(ljlib_paths, srcdir .. "/" .. f) end

  -- lj_vm: peobj on Windows (a ready-to-link object), elfasm/machasm
  -- elsewhere (assembly that still needs compiling).
  local ljvm_mode = "elfasm"
  if windows then ljvm_mode = "peobj"
  elseif opts.target_os == "macos" then ljvm_mode = "machasm" end

  local lj_vm_gen = windows and (builddir .. "/lj_vm.obj") or (builddir .. "/lj_vm.S")
  build:build(lj_vm_gen, "buildvm_gen", {}, { buildvm_exe }, nil, { mode = ljvm_mode })

  local lj_vm_obj = lj_vm_gen
  if not windows then
    lj_vm_obj = builddir .. "/lj_vm.obj"
    build:build(lj_vm_obj, "cc", lj_vm_gen)
  end
  build:newline()

  -- Generated headers (bytecode/ffi/lib/record/fold defs) and jit/vmdef.lua.
  local lj_bcdef_h = srcdir .. "/lj_bcdef.h"
  build:build(lj_bcdef_h, "buildvm_gen", ljlib_paths, { buildvm_exe }, nil, { mode = "bcdef" })
  local lj_ffdef_h = srcdir .. "/lj_ffdef.h"
  build:build(lj_ffdef_h, "buildvm_gen", ljlib_paths, { buildvm_exe }, nil, { mode = "ffdef" })
  local lj_libdef_h = srcdir .. "/lj_libdef.h"
  build:build(lj_libdef_h, "buildvm_gen", ljlib_paths, { buildvm_exe }, nil, { mode = "libdef" })
  local lj_recdef_h = srcdir .. "/lj_recdef.h"
  build:build(lj_recdef_h, "buildvm_gen", ljlib_paths, { buildvm_exe }, nil, { mode = "recdef" })
  local lj_folddef_h = srcdir .. "/lj_folddef.h"
  build:build(lj_folddef_h, "buildvm_gen", srcdir .. "/lj_opt_fold.c",
    { buildvm_exe }, nil, { mode = "folddef" })
  local vmdef_lua = srcdir .. "/jit/vmdef.lua"
  build:build(vmdef_lua, "buildvm_gen", ljlib_paths, { buildvm_exe }, nil, { mode = "vmdef" })
  build:newline()

  local all_hdrgen = {
    lj_bcdef_h, lj_ffdef_h, lj_libdef_h, lj_recdef_h, lj_folddef_h,
    buildvm_arch_h, luajit_h,
  }

  -- Stage 3: compile the LuaJIT core + library sources and link either a
  -- static library or a shared library, plus the luajit executable.
  local core_rule = shared and "cc_dll" or "cc"
  local core_objs = {}
  for _, f in ipairs(LJCORE_C) do
    local obj = builddir .. "/" .. gsub(f, "%.c$", ".obj")
    build:build(obj, core_rule, srcdir .. "/" .. f, all_hdrgen)
    insert(core_objs, obj)
  end
  insert(core_objs, lj_vm_obj)
  build:newline()

  -- Library naming: Windows uses the traditional lua51-based names
  -- (lua51.dll / lua51.lib / liblua51.lib); Linux/macOS keep the
  -- ABI-versioned libluajit-5.1 name from src/Makefile.
  local lib_basename = windows and "lua51" or "luajit-5.1"
  local luajit_lib -- what the executable links against
  local dll_name, implib_name -- only set when shared

  if shared then
    dll_name = windows
      and (builddir .. "/" .. lib_basename .. ".dll")
      or (builddir .. "/lib" .. lib_basename .. (opts.target_os == "macos" and ".dylib" or ".so"))
    if msvc then
      implib_name = builddir .. "/" .. lib_basename .. ".lib"
    elseif windows then -- mingw
      implib_name = builddir .. "/lib" .. lib_basename .. ".dll.a"
    else -- the .so/.dylib itself is what gets linked against on POSIX
      implib_name = dll_name
    end
    local implicit_outputs = (implib_name ~= dll_name) and { implib_name } or nil
    build:build(dll_name, "dll", core_objs, nil, nil, { implib = implib_name }, implicit_outputs)
    luajit_lib = implib_name
  else
    luajit_lib = builddir .. "/lib" .. lib_basename .. (msvc and ".lib" or ".a")
    build:build(luajit_lib, "ar", core_objs)
  end
  build:newline()

  local luajit_obj = builddir .. "/luajit_main.obj"
  build:build(luajit_obj, "cc", srcdir .. "/luajit.c", { luajit_lib })
  build:newline()

  local luajit_t = builddir .. "/luajit" .. exe_ext
  build:build(luajit_t, "link", { luajit_obj, luajit_lib }, { vmdef_lua })
  build:newline()

  local default_targets = { luajit_t }

  if opts.install_dir then
    local installed_exe = opts.install_dir .. "/bin/luajit" .. exe_ext
    build:build(installed_exe, "copy", luajit_t)
    local installed = { installed_exe }
    if shared then
      local installed_dll = opts.install_dir .. "/bin/" .. basename(dll_name)
      build:build(installed_dll, "copy", dll_name)
      insert(installed, installed_dll)
      if implib_name ~= dll_name then
        local installed_implib = opts.install_dir .. "/lib/" .. basename(implib_name)
        build:build(installed_implib, "copy", implib_name)
        insert(installed, installed_implib)
      end
    else
      local installed_lib = opts.install_dir .. "/lib/" .. basename(luajit_lib)
      build:build(installed_lib, "copy", luajit_lib)
      insert(installed, installed_lib)
    end
    build:build("install", "phony", installed)
    -- Note: only the executable and library artifacts are staged; headers
    -- and the pkg-config file are not installed by this generator.
  end

  if opts.with_tests then
    stderr:write("configure.lua: warning: --with-tests was requested, but ",
      "this generator does not yet produce a test build graph.\n")
  end
  if opts.with_bench then
    stderr:write("configure.lua: warning: --with-bench was requested, but ",
      "this generator does not yet wire up a benchmark step.\n")
  end

  build:default(default_targets)
  build:close()
end

local function generate(ninja, opts)
  gen_tools(ninja, opts)
  gen_config(ninja, opts)
  gen_build(ninja, opts)
end


local function readfile(filepath)
  local fp = assert(io.open(filepath))
  local s = fp:read("*a")
  assert(fp:close())
  return s
end

local prefix
if not require then
  local _require_cache = {}
  function require(name)
    if _require_cache[name] ~= nil then
      return _require_cache[name]
    end
    local filename = name .. ".lua"
    local filepath = prefix .. filename
    local s = readfile(filepath)
    _require_cache[name] = assert(loadstring(s, "@"..filename))()
    return _require_cache[name]
  end
end

